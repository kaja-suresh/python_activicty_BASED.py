# Experiment 15: Type Conversion

num1 = input("Enter an integer: ")
num2 = input("Enter a decimal number: ")

integer_value = int(num1)
float_value = float(num2)

print("Integer value =", integer_value)
print("Float value =", float_value)

print("Integer to float =", float(integer_value))
print("Float to integer =", int(float_value))
print("Integer to string =", str(integer_value))
